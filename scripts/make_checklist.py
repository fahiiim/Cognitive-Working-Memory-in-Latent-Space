"""Write paper/sections/checklist.tex from the official NeurIPS template checklist, filling the
16 answers below in order. Questions and guidelines are copied verbatim from the template.

    .venv\\Scripts\\python.exe scripts\\make_checklist.py paper\\template\\neurips_2025_template.tex
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

ANSWERS = [
    ("Yes", "The abstract and \\cref{sec:intro} state each claim with the experiment that tests it; "
            "\\texttt{paper/claims\\_map.md} maps every number to its source file."),
    ("Yes", "\\Cref{sec:limitations} discusses the tasks, the architecture class, the loose maze bound, "
            "and the cases where simple confidence rules suffice."),
    ("Yes", "Assumptions are stated in \\cref{sec:theory}; full proofs are in \\cref{app:proofs}, and each "
            "result has an executable check in \\texttt{tests/test\\_theory.py}."),
    ("Yes", "\\Cref{app:details} lists every hyperparameter, split and selection rule; one YAML config per run "
            "and \\texttt{REPRODUCE.md} give the exact commands."),
    ("Yes", "All code, configs, frozen-split hashes and the analysis notebooks are released; the data are "
            "generated from fixed seeds."),
    ("Yes", "\\Cref{sec:benchmark,sec:method} and \\cref{app:details} give splits, objectives, optimiser, "
            "schedules, threshold grids and the ID-val selection rule."),
    ("Yes", "95\\% bootstrap confidence intervals over instances (clustered by seed), Wilcoxon tests across "
            "seeds and Holm correction; \\cref{sec:experiments}."),
    ("Yes", "One RTX 5070; GPU-hours per sweep are reported in \\cref{app:details}."),
    ("Yes", "The work uses synthetic data only and follows the NeurIPS Code of Ethics."),
    ("NA", "Foundational research on halting in small synthetic-task models; we see no direct societal "
           "impact beyond general efficiency of iterative models."),
    ("NA", "No pretrained language or image models or scraped data are released."),
    ("Yes", "PyTorch (BSD) and the arXiv metadata used for the bibliography are credited; maze data are "
            "generated by our own code."),
    ("Yes", "The DepthShift generators and stopping-rule library are documented in the repository README "
            "and \\texttt{REPRODUCE.md}."),
    ("NA", "No crowdsourcing or human subjects."),
    ("NA", "No human subjects."),
    ("Yes", "An AI coding assistant was used to write code and draft text under the author's direction; all "
            "results come from the released code and were checked by the author. LLMs are not part of the method."),
]


def main(template: str) -> None:
    t = Path(template).read_text(encoding="utf-8")
    body = t[t.index("%%% END INSTRUCTIONS %%%") + len("%%% END INSTRUCTIONS %%%") : t.rindex("\\end{document}")]
    assert body.count("\\answerTODO{}") == len(ANSWERS) == body.count("\\justificationTODO{}")
    for ans, just in ANSWERS:
        body = body.replace("\\answerTODO{}", f"\\answer{ans}{{}}", 1)
        body = body.replace("\\justificationTODO{}", just, 1)
    out = ROOT / "paper" / "sections" / "checklist.tex"
    out.write_text("\\newpage\n\\section*{NeurIPS Paper Checklist}\n" + body.strip() + "\n", encoding="utf-8")
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main(sys.argv[1])
