"""T3: perfect mazes in the style of the easy-to-hard-data maze datasets.

An n x n cell maze is generated by randomised depth-first search and rendered on a
(2n+1) x (2n+1) pixel grid (walls 0, corridors 1). Input channels: [open, start, goal].
Target: 1 on the unique start-goal path, 0 elsewhere. Two depth proxies:

- path_len: number of path pixels minus one;
- fill_depth: iterations of dead-end filling (remove open non-terminal pixels with at most one
  open 4-neighbour) until nothing changes. Dead-end filling is itself a local algorithm (radius 1
  per iteration), so it gives an achievable local step count, not a lower bound.
"""

from __future__ import annotations

import numpy as np
import torch
import torch.nn.functional as F

N_IN = 3
N_OUT = 2


def generate_maze(n: int, rng: np.random.Generator) -> tuple[np.ndarray, tuple[int, int], tuple[int, int]]:
    size = 2 * n + 1
    grid = np.zeros((size, size), dtype=np.uint8)
    visited = np.zeros((n, n), dtype=bool)
    start = (int(rng.integers(n)), int(rng.integers(n)))
    stack = [start]
    visited[start] = True
    grid[2 * start[0] + 1, 2 * start[1] + 1] = 1
    moves = np.array([(0, 1), (1, 0), (0, -1), (-1, 0)])
    while stack:
        r, c = stack[-1]
        nbrs = [(r + dr, c + dc) for dr, dc in moves if 0 <= r + dr < n and 0 <= c + dc < n and not visited[r + dr, c + dc]]
        if not nbrs:
            stack.pop()
            continue
        nr, nc = nbrs[int(rng.integers(len(nbrs)))]
        visited[nr, nc] = True
        grid[2 * nr + 1, 2 * nc + 1] = 1
        grid[r + nr + 1, c + nc + 1] = 1  # knock down the wall between the two cells
        stack.append((nr, nc))
    cells = rng.choice(n * n, size=2, replace=False)
    s = (2 * (cells[0] // n) + 1, 2 * (cells[0] % n) + 1)
    g = (2 * (cells[1] // n) + 1, 2 * (cells[1] % n) + 1)
    return grid, s, g


def solve_path(grid: np.ndarray, s: tuple[int, int], g: tuple[int, int]) -> np.ndarray:
    """BFS on pixels; returns the 0/1 mask of the unique path (perfect maze)."""
    H, W = grid.shape
    prev = -np.ones((H, W, 2), dtype=np.int32)
    seen = np.zeros_like(grid, dtype=bool)
    q = [s]
    seen[s] = True
    head = 0
    while head < len(q):
        r, c = q[head]
        head += 1
        if (r, c) == g:
            break
        for dr, dc in ((0, 1), (1, 0), (0, -1), (-1, 0)):
            nr, nc = r + dr, c + dc
            if 0 <= nr < H and 0 <= nc < W and grid[nr, nc] and not seen[nr, nc]:
                seen[nr, nc] = True
                prev[nr, nc] = (r, c)
                q.append((nr, nc))
    path = np.zeros_like(grid)
    cur = g
    while cur != (-1, -1):
        path[cur] = 1
        if cur == s:
            break
        cur = tuple(int(v) for v in prev[cur])
    return path


def dead_end_fill_depth(open_: torch.Tensor, start: torch.Tensor, goal: torch.Tensor, max_iter: int = 100000):
    """Vectorised dead-end filling. open_, start, goal: [B, H, W] bool. Returns (depth [B], path [B,H,W])."""
    k = torch.tensor([[0, 1, 0], [1, 0, 1], [0, 1, 0]], dtype=torch.float32, device=open_.device)[None, None]
    cur = open_.clone()
    depth = torch.zeros(open_.shape[0], dtype=torch.long, device=open_.device)
    term = start | goal
    for _ in range(max_iter):
        nb = F.conv2d(cur.float()[:, None], k, padding=1)[:, 0]
        remove = cur & ~term & (nb <= 1)
        changed = remove.flatten(1).any(1)
        if not changed.any():
            break
        depth += changed.long()
        cur = cur & ~remove
    return depth, cur


def make_mazes(count: int, n: int, seed: int) -> dict[str, torch.Tensor]:
    rng = np.random.default_rng(seed)
    xs, ys, plen = [], [], []
    for _ in range(count):
        grid, s, g = generate_maze(n, rng)
        path = solve_path(grid, s, g)
        img = np.zeros((3,) + grid.shape, dtype=np.uint8)
        img[0] = grid
        img[1][s] = 1
        img[2][g] = 1
        xs.append(img)
        ys.append(path)
        plen.append(int(path.sum()) - 1)
    x = torch.from_numpy(np.stack(xs))
    y = torch.from_numpy(np.stack(ys)).long()
    fill, _ = dead_end_fill_depth(x[:, 0].bool(), x[:, 1].bool(), x[:, 2].bool())
    return {
        "x": x,
        "y": y,
        "size": torch.full((count,), n, dtype=torch.long),
        "path_len": torch.tensor(plen, dtype=torch.long),
        "depth": fill,
    }


def augment_dihedral(x: torch.Tensor, y: torch.Tensor, g: torch.Generator) -> tuple[torch.Tensor, torch.Tensor]:
    """Random rotation by k*90 degrees and optional flip, one choice per batch."""
    k = int(torch.randint(0, 4, (1,), generator=g, device=g.device).item())
    flip = bool(torch.randint(0, 2, (1,), generator=g, device=g.device).item())
    x, y = torch.rot90(x, k, dims=(-2, -1)), torch.rot90(y, k, dims=(-2, -1))
    if flip:
        x, y = x.flip(-1), y.flip(-1)
    return x, y
